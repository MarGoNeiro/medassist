// ── Быстрые lookup-таблицы (строятся один раз при импорте) ─────────────────

/** dagger-код → массив asterisk-кодов */
export const dagToAst = {}
/** asterisk-код → массив dagger-кодов */
export const astToDag = {}

for (const [d, a] of CROSS_REF_PAIRS) {
  ;(dagToAst[d] = dagToAst[d] || []).push(a)
  ;(astToDag[a] = astToDag[a] || []).push(d)
}

/**
 * Возвращает перекрёстные ссылки для кода.
 * result.dagRefs  — этот код является †, список * кодов-проявлений
 * result.astRefs  — этот код является *, список † кодов-этиологий
 */
export function getCrossRefs(code) {
  return {
    dagRefs: dagToAst[code] || [],   // → ищи ещё *
    astRefs: astToDag[code] || [],   // ← причина †
  }
}
